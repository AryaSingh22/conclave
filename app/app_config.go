// Conclave chain identity (SPEC §0 Naming Canon).
const (
	// AppName is the ABCI application name.
	AppName = "conclave"

	// Bech32Prefix is the human-readable part of all Conclave addresses
	// (accounts conc1..., validators concvaloper1...) per SPEC §0.
	Bech32Prefix          = "conc"
	Bech32PrefixValidator = Bech32Prefix + "valoper"
	Bech32PrefixConsensus = Bech32Prefix + "valcons"

	// BaseDenom is the native staking/gas token base denom: 10^6 uclv = 1 CLV (SPEC §0).
	BaseDenom    = "uclv"
	DisplayDenom = "clv"

	// MockUSDCDenom is the dev-only stable settlement asset minted at genesis (SPEC §3).
	MockUSDCDenom = "uusdc"
)

var (
	// module account permissions
	moduleAccPerms = []*authmodulev1.ModuleAccountPermission{
		{Account: authtypes.FeeCollectorName},
		{Account: distrtypes.ModuleName},
		{Account: minttypes.ModuleName, Permissions: []string{authtypes.Minter}},
		{Account: stakingtypes.BondedPoolName, Permissions: []string{authtypes.Burner, stakingtypes.ModuleName}},
		{Account: stakingtypes.NotBondedPoolName, Permissions: []string{authtypes.Burner, stakingtypes.ModuleName}},
		{Account: govtypes.ModuleName, Permissions: []string{authtypes.Burner}},
		{Account: ibctransfertypes.ModuleName, Permissions: []string{authtypes.Minter, authtypes.Burner}},
		// the mandate module account is the SPEC §6.2 fee-conversion pool:
		// a genesis-funded CLV float that accumulates converted fee denoms;
		// it never mints or burns
		{Account: mandatetypes.ModuleName},
	}

	// blocked account addresses (module accounts that must not receive user funds)
	blockAccAddrs = []string{
		authtypes.FeeCollectorName,
		distrtypes.ModuleName,
		minttypes.ModuleName,
		stakingtypes.BondedPoolName,
		stakingtypes.NotBondedPoolName,
		ibctransfertypes.ModuleName,
		mandatetypes.ModuleName,
		// the gov module account is allowed to receive funds (deposits)
	}

	// AppConfig is the depinject application configuration (SPEC §3: depinject +
	// module wiring per Cosmos SDK v0.50 conventions).
	//
	// The IBC modules (capability, ibc, transfer, light clients) do not support
	// depinject in ibc-go v8; they are wired manually in app.go via
	// RegisterStores/RegisterModules. Their module names still appear in the
	// ordering lists below — runtime.App.Load applies these orderings after
	// manual registration.
	AppConfig = depinject.Configs(appconfig.Compose(&appv1alpha1.Config{
		Modules: []*appv1alpha1.ModuleConfig{
			{
				Name: runtime.ModuleName,
				Config: appconfig.WrapAny(&runtimev1alpha1.Module{
					AppName: AppName,
					// NOTE: upgrade module is required to be prioritized
					PreBlockers: []string{
						upgradetypes.ModuleName,
					},
					// During begin block slashing happens after distr.BeginBlocker so that
					// there is nothing left over in the validator fee pool, so as to keep the
					// CanWithdrawInvariant invariant.
					// NOTE: staking module is required if HistoricalEntries param > 0
					// NOTE: capability module's beginblocker must come before any
					// modules using capabilities (e.g. IBC)
					BeginBlockers: []string{
						capabilitytypes.ModuleName,
						minttypes.ModuleName,
						distrtypes.ModuleName,
						slashingtypes.ModuleName,
						evidencetypes.ModuleName,
						stakingtypes.ModuleName,
						ibcexported.ModuleName,
						ibctransfertypes.ModuleName,
						authz.ModuleName,
					},
					EndBlockers: []string{
						crisistypes.ModuleName,
						govtypes.ModuleName,
						stakingtypes.ModuleName,
						ibcexported.ModuleName,
						ibctransfertypes.ModuleName,
						capabilitytypes.ModuleName,
						feegrant.ModuleName,
						// SPEC §6.7 unordered dedup-cache sweep (app-level
						// shim, manually registered)
						unorderedtypes.ModuleName,
					},
					OverrideStoreKeys: []*runtimev1alpha1.StoreKeyConfig{
						{
							ModuleName: authtypes.ModuleName,
							KvStoreKey: "acc",
						},
					},
					// NOTE: The genutils module must occur after staking so that pools are
					// properly initialized with tokens from genesis accounts.
					// NOTE: The genutils module must also occur after auth so that it can access the params from auth.
					// NOTE: Capability module must occur first so that it can initialize any capabilities
					// so that other modules that want to create or claim capabilities afterwards in InitChain
					// can do so safely.
					InitGenesis: []string{
						capabilitytypes.ModuleName,
						authtypes.ModuleName,
						banktypes.ModuleName,
						distrtypes.ModuleName,
						stakingtypes.ModuleName,
						slashingtypes.ModuleName,
						govtypes.ModuleName,
						minttypes.ModuleName,
						crisistypes.ModuleName,
						ibcexported.ModuleName,
						ibctransfertypes.ModuleName,
						genutiltypes.ModuleName,
						evidencetypes.ModuleName,
						authz.ModuleName,
						feegrant.ModuleName,
						paramstypes.ModuleName,
						upgradetypes.ModuleName,
						vestingtypes.ModuleName,
						// Conclave modules (manually registered, SPEC §10 order)
						sigiltypes.ModuleName,
						mandatetypes.ModuleName,
					},
				}),
			},
			{
				Name: authtypes.ModuleName,
				Config: appconfig.WrapAny(&authmodulev1.Module{
					Bech32Prefix:             Bech32Prefix,
					ModuleAccountPermissions: moduleAccPerms,
				}),
			},
			{
				Name:   vestingtypes.ModuleName,
				Config: appconfig.WrapAny(&vestingmodulev1.Module{}),
			},
			{
				Name: banktypes.ModuleName,
				Config: appconfig.WrapAny(&bankmodulev1.Module{
					BlockedModuleAccountsOverride: blockAccAddrs,
				}),
			},
			{
				Name: stakingtypes.ModuleName,
				Config: appconfig.WrapAny(&stakingmodulev1.Module{
					Bech32PrefixValidator: Bech32PrefixValidator,
					Bech32PrefixConsensus: Bech32PrefixConsensus,
				}),
			},
			{
				Name:   slashingtypes.ModuleName,
				Config: appconfig.WrapAny(&slashingmodulev1.Module{}),
			},
			{
				Name:   paramstypes.ModuleName,
				Config: appconfig.WrapAny(&paramsmodulev1.Module{}),
			},
			{
				Name: "tx",
				Config: appconfig.WrapAny(&txconfigv1.Config{
					// the Conclave ante pipeline is set explicitly in app.go;
					// task 0.4 extends it with MandateDecorator (SPEC §6.2)
					SkipAnteHandler: true,
				}),
			},
			{
				Name:   genutiltypes.ModuleName,
				Config: appconfig.WrapAny(&genutilmodulev1.Module{}),
			},
			{
				Name:   authz.ModuleName,
				Config: appconfig.WrapAny(&authzmodulev1.Module{}),
			},
			{
				Name:   upgradetypes.ModuleName,
				Config: appconfig.WrapAny(&upgrademodulev1.Module{}),
			},
			{
				Name:   distrtypes.ModuleName,
				Config: appconfig.WrapAny(&distrmodulev1.Module{}),
			},
			{
				Name:   evidencetypes.ModuleName,
				Config: appconfig.WrapAny(&evidencemodulev1.Module{}),
			},
			{
				Name:   minttypes.ModuleName,
				Config: appconfig.WrapAny(&mintmodulev1.Module{}),
			},
			{
				Name:   feegrant.ModuleName,
				Config: appconfig.WrapAny(&feegrantmodulev1.Module{}),
			},
			{
				Name:   govtypes.ModuleName,
				Config: appconfig.WrapAny(&govmodulev1.Module{}),
			},
			{
				Name:   crisistypes.ModuleName,
				Config: appconfig.WrapAny(&crisismodulev1.Module{}),
			},
			{
				Name:   consensustypes.ModuleName,
				Config: appconfig.WrapAny(&consensusmodulev1.Module{}),
			},
		},
	}),
		depinject.Supply(
			// supply custom module basics
			map[string]module.AppModuleBasic{
				genutiltypes.ModuleName: genutil.NewAppModuleBasic(genutiltypes.DefaultMessageValidator),
				govtypes.ModuleName: gov.NewAppModuleBasic(
					[]govclient.ProposalHandler{
						paramsclient.ProposalHandler,
					},
				),
			},
		))
)
